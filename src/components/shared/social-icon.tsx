/** Brand or generic icon for a social platform key. Decorative: pair with a label. */
export function SocialIcon({ platform, className }: { platform: string; className?: string }) {
  const classes = cn("size-4", className);
  const path = brandPaths[platform];
  if (path) {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" className={classes} aria-hidden="true">
        <path d={path} />
      </svg>
    );
  }
  switch (platform) {
    case "instagram":
      return <Instagram className={classes} />;
    case "dribbble":
      return <Dribbble className={classes} />;
    case "email":
      return <Mail className={classes} aria-hidden="true" />;
    case "devto":
      return <Code2 className={classes} aria-hidden="true" />;
    default:
      return <Globe className={classes} aria-hidden="true" />;
  }
}
